import { createConfig, http, injected } from "wagmi";
import { defineChain } from "viem";
import type { PublicConfig } from "./api";

export function labChain(cfg: PublicConfig) {
  return defineChain({
    id: cfg.chainId,
    name: cfg.chainName,
    nativeCurrency: { name: "BNB", symbol: cfg.nativeSymbol, decimals: 18 },
    rpcUrls: { default: { http: [cfg.rpcUrl], webSocket: [cfg.wsUrl] } },
    blockExplorers: { default: { name: "Blockscout", url: cfg.blockscoutUrl } },
  });
}

export function wagmiConfig(cfg: PublicConfig) {
  const chain = labChain(cfg);
  return createConfig({
    chains: [chain],
    connectors: [injected()],
    transports: { [chain.id]: http(cfg.rpcUrl) },
    ssr: false,
  });
}

